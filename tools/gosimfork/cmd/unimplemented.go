package main

import (
	"bufio"
	"bytes"
	"fmt"
	"os"
	"os/exec"
	"slices"
	"strings"

	"github.com/jellevandenhooff/gosim/internal/gosimtool"
)

// writeUnimplemented writes the names of the unimplemented hooks to path, one
// per line.
func writeUnimplemented(path string, hooks []gosimtool.UnimplementedHook) error {
	var b bytes.Buffer
	b.WriteString("# Code generated by gosim translate -unimplemented. DO NOT EDIT.\n")
	b.WriteString("# Hooks in the translated code that fail through gosimruntime.Unimplemented.\n")
	for i, hook := range hooks {
		if i > 0 && hooks[i-1].Name == hook.Name {
			continue
		}
		b.WriteString(hook.Name + "\n")
	}
	return os.WriteFile(path, b.Bytes(), 0o644)
}

// readHookNames reads a file of hook names, one per line. A # starts a
// comment.
func readHookNames(path string) (map[string]bool, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	names := make(map[string]bool)
	for _, line := range strings.Split(string(b), "\n") {
		line, _, _ = strings.Cut(line, "#")
		if line = strings.TrimSpace(line); line != "" {
			names[line] = true
		}
	}
	return names, nil
}

// checkUnimplemented fails when binary can reach an unimplemented hook that is
// not in allowed.
func checkUnimplemented(binary string, hooks []gosimtool.UnimplementedHook, allowed map[string]bool) error {
	linked, err := linkedUnimplemented(binary, hooks)
	if err != nil {
		return err
	}
	var refused []string
	for _, hook := range linked {
		if !allowed[hook.Name] {
			refused = append(refused, hook.Name)
		}
	}
	refused = slices.Compact(refused)
	if len(refused) > 0 {
		return fmt.Errorf("the test binary can reach these unimplemented hooks:\n\t%s\nImplement them, or list them in the -allow-unimplemented file with the reason the tests never call them", strings.Join(refused, "\n\t"))
	}
	return nil
}

// linkedUnimplemented returns the unimplemented hooks whose functions the
// linker kept in binary. The linker keeps only functions that the program's
// code can reach, so the result is a cheap call graph check.
func linkedUnimplemented(binary string, hooks []gosimtool.UnimplementedHook) ([]gosimtool.UnimplementedHook, error) {
	out, err := exec.Command("go", "tool", "nm", binary).Output()
	if err != nil {
		return nil, fmt.Errorf("listing the symbols of %s: %w", binary, err)
	}
	symbols := make(map[string]bool)
	scanner := bufio.NewScanner(bytes.NewReader(out))
	for scanner.Scan() {
		// Each line is: address type name
		fields := strings.Fields(scanner.Text())
		if len(fields) >= 3 && (fields[1] == "T" || fields[1] == "t") {
			symbols[fields[2]] = true
		}
	}
	var linked []gosimtool.UnimplementedHook
	for _, hook := range hooks {
		if symbols[hook.Symbol] {
			linked = append(linked, hook)
		}
	}
	return linked, nil
}
